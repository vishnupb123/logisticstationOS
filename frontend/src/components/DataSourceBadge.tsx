// Milestone 10's exit criterion, literally: "every view states the
// source and status of each metric it shows (synthetic/simulated vs.
// whatever 'real' means at that point) — simulated data is never
// presented as live operational information." There is no "live"
// option here by design — StationOS has no real operational system
// to be live against yet (ADR-0002/ADR-0006); offering one would
// invite exactly the confusion this badge exists to prevent.
import "./DataSourceBadge.css";

export type DataSourceKind = "synthetic" | "simulated";

const LABEL: Record<DataSourceKind, string> = {
  synthetic: "Synthetic data",
  simulated: "Simulated run",
};

const EXPLANATION: Record<DataSourceKind, string> = {
  synthetic:
    "Generated by StationOS's own seeded synthetic event generator (Milestone 2) — never real operational, employee, or customer data.",
  simulated:
    "Produced by the digital twin / RL environment (Milestones 4 & 6) — a hypothetical run, not a record of anything that happened.",
};

export function DataSourceBadge({ kind }: { kind: DataSourceKind }) {
  return (
    <span className={`data-source-badge data-source-badge--${kind}`} title={EXPLANATION[kind]}>
      {LABEL[kind]}
    </span>
  );
}
